void rc_clear(uint32_t *px, int w, int h, uint32_t color)
{
    for(int i=0;i<w*h;i++) px[i] = color;
}

void rc_fill(uint32_t *px, int W, int H, int x, int y, int w, int h, uint32_t color)
{
    /* foreground colors arrive 24-bit; the buffer is ARGB so the alpha byte
       must be forced opaque or the compositor blends the pixel away.
       color 0 stays transparent: icons use it as a "punch" to the background */
    uint32_t c = color ? (color | 0xFF000000u) : 0u;
    for(int yy=y; yy<y+h; yy++){
        if(yy<0||yy>=H) continue;
        for(int xx=x; xx<x+w; xx++){
            if(xx<0||xx>=W) continue;
            px[yy*W+xx] = c;
        }
    }
}

static void glyph(uint32_t *px, int W, int H, int x, int y, char ch, uint32_t color)
{
    if(ch < 32 || ch > 126) ch = '?';
    const uint8_t *g = font[ch-32];
    for(int row=0; row<8; row++){
        int yy = y+row;
        if(yy<0||yy>=H) continue;
        for(int col=0; col<8; col++){
            if(!(g[row] & (1<<col))) continue;
            int xx = x + col;
            if(xx<0||xx>=W) continue;
            px[yy*W+xx] = color | 0xFF000000u; /* opaque glyph pixel */
        }
    }
}

int rc_text(uint32_t *px, int W, int H, int x, int y, const char *s, uint32_t color)
{
    int n = 0;
    for(; *s; s++, n++) glyph(px, W, H, x + n*9, y, *s, color);
    return n*9;
}

int rc_text_width(const char *s)
{
    int n = 0; for(; *s; s++) n++; return n*9;
}

/* ------- custom icons: 12x12 hand-made ------- */

int rc_icon_battery(uint32_t *px, int W, int H, int x, int y, int pct, uint32_t color)
{
    rc_fill(px, W, H, x, y+2, 11, 8, color);          /* body outline-ish */
    rc_fill(px, W, H, x+11, y+4, 2, 4, color);        /* nub */
    rc_fill(px, W, H, x+1, y+3, 9, 6, 0);             /* hollow */
    int fill = pct > 100 ? 9 : pct*9/100;
    rc_fill(px, W, H, x+1, y+3, fill, 6, color);      /* charge */
    return 14;
}

int rc_icon_volume(uint32_t *px, int W, int H, int x, int y, int lvl, uint32_t color)
{
    rc_fill(px, W, H, x, y+4, 3, 4, color);           /* box */
    for(int i=0;i<3;i++)                              /* cone */
        rc_fill(px, W, H, x+3+i, y+3-i, 1, 4+2*i, color);
    for(int i=0;i<lvl && i<3;i++)                     /* waves */
        rc_fill(px, W, H, x+8+i*2, y+4-i*2, 1, 4+i*4, color);
    return 14;
}

int rc_icon_network(uint32_t *px, int W, int H, int x, int y, bool up, uint32_t color)
{
    /* arcs: three stacked bars widening = signal */
    rc_fill(px, W, H, x, y+9, 3, 3, color);
    rc_fill(px, W, H, x+4, y+5, 3, 7, color);
    rc_fill(px, W, H, x+8, y+1, 3, 11, color);
    if(!up) rc_fill(px, W, H, x-1, y+10, 13, 1, 0);   /* cut = down */
    return 13;
}

int rc_icon_cpu(uint32_t *px, int W, int H, int x, int y, int load, uint32_t color)
{
    rc_fill(px, W, H, x+1, y+1, 10, 10, color);       /* die */
    rc_fill(px, W, H, x+2, y+2, 8, 8, 0);
    int inner = load > 100 ? 8 : load*8/100;          /* load fill */
    rc_fill(px, W, H, x+2, y+10-2-inner+0, 8, inner, color);
    for(int i=0;i<3;i++){                              /* pins */
        rc_fill(px, W, H, x+2+i*3, y-1, 1, 2, color);
        rc_fill(px, W, H, x+2+i*3, y+11, 1, 2, color);
        rc_fill(px, W, H, x-1, y+2+i*3, 2, 1, color);
        rc_fill(px, W, H, x+11, y+2+i*3, 2, 1, color);
    }
    return 14;
}
